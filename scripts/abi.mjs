#!/usr/bin/env node
// Generates the typed ABI the web app is compiled against from the compiled contract.
//
//   node scripts/abi.mjs           write web/src/abi/AssertDAO.ts
//   node scripts/abi.mjs --check   fail if the committed file is out of date
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import prettier from 'prettier';
import { contracts, fail, root, run } from './lib.mjs';

const target = join(root, 'web/src/abi/AssertDAO.ts');

run('forge', ['build', '--skip', './test/**', './script/**'], { stdio: 'ignore' });
const { abi } = JSON.parse(readFileSync(join(contracts, 'out/AssertDAO.sol/AssertDAO.json'), 'utf8'));

const source = await prettier.format(
  `// Generated by scripts/abi.mjs from the compiled contract. Do not edit: run \`npm run abi\`.\n` +
    `export const assertDaoAbi = ${JSON.stringify(abi)} as const;\n`,
  { ...(await prettier.resolveConfig(target)), filepath: target },
);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // A missing file is out of date.
  }
  if (current !== source) fail(`${relative(root, target)} is out of date. Run \`npm run abi\` and commit the result.`);
  console.log(`✓ ${relative(root, target)} matches the contract`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
  console.log(`✓ wrote ${relative(root, target)}`);
}
